/**
 * Generates a Google Earth Web URL that flies directly to the exact WGS84 coordinates,
 * automatically queries the location through the Google Earth geocoder, and drops an exact
 * search placemark pin marker on the location.
 */
export function getGoogleEarthWebUrl(lat: number, lng: number, distanceMeters = 1200): string {
  const safeLat = Number(lat.toFixed(6))
  const safeLng = Number(lng.toFixed(6))
  // The /search/ endpoint instructs Google Earth for Web to execute a coordinate search,
  // populating the search result card with the coordinates and displaying a pin on the globe.
  return `https://earth.google.com/web/search/${safeLat},+${safeLng}/@${safeLat},${safeLng},0a,${distanceMeters}d,35y,0h,0t,0r`
}

/**
 * Generates an official Google Maps URL that opens the exact coordinates with a dropped pin.
 */
export function getGoogleMapsUrl(lat: number, lng: number): string {
  const safeLat = Number(lat.toFixed(6))
  const safeLng = Number(lng.toFixed(6))
  return `https://www.google.com/maps/search/?api=1&query=${safeLat},${safeLng}`
}

/**
 * Generates a Google Maps Satellite URL that immediately opens high-resolution satellite imagery
 * with an unmistakable dropped red pin marker pinned right at the coordinates.
 */
export function getGoogleMapsSatelliteUrl(lat: number, lng: number): string {
  const safeLat = Number(lat.toFixed(6))
  const safeLng = Number(lng.toFixed(6))
  // q=loc:lat,lng with t=k forces a red pin marker on satellite aerial imagery
  return `https://maps.google.com/?q=loc:${safeLat},${safeLng}&t=k`
}

/**
 * Generates an official KML Placemark XML string with a styled 3D red pushpin,
 * site coordinates, and municipality metadata.
 */
export function generateKmlPlacemark(lat: number, lng: number, siteTitle?: string): string {
  const safeLat = Number(lat.toFixed(6))
  const safeLng = Number(lng.toFixed(6))
  const title = siteTitle || `BUILD-SAFE Site (${safeLat.toFixed(5)}° N, ${safeLng.toFixed(5)}° E)`
  return `<?xml version="1.0" encoding="UTF-8"?>
<kml xmlns="http://www.opengis.net/kml/2.2">
  <Document>
    <name>${escapeXml(title)}</name>
    <Style id="buildSafePin">
      <IconStyle>
        <scale>1.3</scale>
        <Icon>
          <href>http://maps.google.com/mapfiles/kml/pushpin/red-pushpin.png</href>
        </Icon>
        <hotSpot x="20" y="2" xunits="pixels" yunits="pixels"/>
      </IconStyle>
      <LabelStyle>
        <scale>1.0</scale>
      </LabelStyle>
    </Style>
    <Placemark>
      <name>${escapeXml(title)}</name>
      <description><![CDATA[
        <div style="font-family:system-ui,sans-serif;font-size:13px;line-height:1.5;">
          <h3 style="margin:0 0 8px;color:#047857;">BUILD-SAFE Lasam Assessment Point</h3>
          <p><b>Coordinates:</b> ${safeLat.toFixed(5)}° N, ${safeLng.toFixed(5)}° E</p>
          <p><b>Target:</b> ${escapeXml(title)}</p>
          <p><b>Municipality:</b> Lasam, Cagayan</p>
          <p style="color:#64748b;font-size:11px;margin-top:8px;">Generated by BUILD-SAFE Lasam Multi-Hazard &amp; Zoning Decision Support Platform</p>
        </div>
      ]]></description>
      <styleUrl>#buildSafePin</styleUrl>
      <Point>
        <coordinates>${safeLng},${safeLat},0</coordinates>
      </Point>
    </Placemark>
  </Document>
</kml>`
}

function escapeXml(unsafe: string): string {
  return unsafe.replace(/[<>&'"]/g, (c) => {
    switch (c) {
      case '<': return '&lt;'
      case '>': return '&gt;'
      case '&': return '&amp;'
      case '\'': return '&apos;'
      case '"': return '&quot;'
      default: return c
    }
  })
}

/**
 * Downloads a .kml placemark file that opens natively in Google Earth Desktop or Mobile
 * with a 3D red pushpin right at the assessed coordinates.
 */
export function downloadKmlPlacemark(lat: number, lng: number, siteTitle?: string): void {
  const kml = generateKmlPlacemark(lat, lng, siteTitle)
  const safeLat = Number(lat.toFixed(6))
  const safeLng = Number(lng.toFixed(6))
  const blob = new Blob([kml], { type: 'application/vnd.google-earth.kml+xml;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const a = document.createElement('a')
  a.href = url
  a.download = `buildsafe-site-${safeLat.toFixed(5)}_${safeLng.toFixed(5)}.kml`
  document.body.appendChild(a)
  a.click()
  document.body.removeChild(a)
  URL.revokeObjectURL(url)
}
